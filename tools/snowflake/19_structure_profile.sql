-- The structure of the two source tables, for building a synthetic copy outside work: column shapes,
-- the row grain, how DIST_CH, CHANNEL, PRODUCT_V2, ZIP_CODE, FIRM / PARENT and the people relate, where MM_OPP
-- sits, and the shape (not the size) of every amount.  Safe to bring back: no names, no ID values,
-- no DIST_CH or PRODUCT_V2 values, no amounts.  SOURCE is firm_1 / firm_2 (in SOURCE order, as in 13
-- and 16); DIST_CH values (either table) are D1_01, D1_02, ... (D2_.. for firm_2) and PRODUCT_V2 values
-- PR01, ..., numbered by row count, the same codes as 20_masked_extract.sql; target CHANNEL values are kept.  A distribution of amounts is divided by its
-- own median (METRIC ends "/ median", P50 = 1): shape only.  Distributions: VALUE = observations.
-- One result set; download it as CSV.  Before sending, read K1, K2 and METRIC: they hold only codes,
-- CHANNEL values, column names and fixed labels.
WITH
u AS (SELECT * FROM ssdb_integration.lr_strategy.data_withnewchannel_union_w_joinkeys),
t AS (SELECT * FROM ssdb_integration.lr_strategy.territories),
lab AS (             -- SOURCE -> firm_1 / firm_2
  SELECT SOURCE, 'firm_' || CAST(DENSE_RANK() OVER (ORDER BY SOURCE) AS VARCHAR) AS SRC
  FROM (SELECT SOURCE FROM u UNION SELECT SOURCE FROM t) x),
carrier AS (SELECT DISTINCT SOURCE FROM u WHERE COALESCE(MM_OPP, 0) <> 0),
dv AS (              -- every DIST_CH value of either table, with its rows in each
  SELECT SOURCE, V, SUM(UN) AS UN, SUM(TN) AS TN
  FROM (SELECT SOURCE, DIST_CH AS V, COUNT(*) AS UN, 0 AS TN FROM u GROUP BY SOURCE, DIST_CH
        UNION ALL
        SELECT SOURCE, CHANNEL, 0, COUNT(*) FROM t GROUP BY SOURCE, CHANNEL) x
  GROUP BY SOURCE, V),
dc AS (              -- DIST_CH -> D1_01.. (D<SOURCE number>_), union rows first, then territories rows; as in 20
  SELECT SOURCE, V, UN, TN,
         CASE WHEN V IS NULL THEN 'NULL'
              ELSE 'D' || CAST(DENSE_RANK() OVER (ORDER BY SOURCE) AS VARCHAR) || '_'
                   || LPAD(CAST(ROW_NUMBER() OVER (PARTITION BY SOURCE ORDER BY CASE WHEN V IS NULL THEN 1 ELSE 0 END, UN DESC, TN DESC, SHA2(V)) AS VARCHAR), 2, '0')
         END AS DC
  FROM dv),
pc AS (              -- PRODUCT_V2 -> PR01..; as in 20
  SELECT PRODUCT_V2 AS V,
         CASE WHEN PRODUCT_V2 IS NULL THEN 'NULL'
              ELSE 'PR' || LPAD(CAST(ROW_NUMBER() OVER (ORDER BY CASE WHEN PRODUCT_V2 IS NULL THEN 1 ELSE 0 END, COUNT(*) DESC, SHA2(PRODUCT_V2)) AS VARCHAR), 2, '0')
         END AS PC
  FROM u GROUP BY PRODUCT_V2),
ux AS (
  SELECT l.SRC, d.DC, p.PC,
         CASE WHEN u.SOURCE IN (SELECT SOURCE FROM carrier) THEN 1 ELSE 0 END AS IS_CARRIER,
         CASE WHEN u.ACTUAL_SALES_AMOUNT > 0 THEN u.ACTUAL_SALES_AMOUNT ELSE 0 END AS POS,
         u.*
  FROM u
  JOIN lab l ON l.SOURCE IS NOT DISTINCT FROM u.SOURCE
  JOIN dc d ON d.SOURCE IS NOT DISTINCT FROM u.SOURCE AND d.V IS NOT DISTINCT FROM u.DIST_CH
  JOIN pc p ON p.V IS NOT DISTINCT FROM u.PRODUCT_V2),
tx AS (
  SELECT l.SRC, d.DC, t.*
  FROM t
  JOIN lab l ON l.SOURCE IS NOT DISTINCT FROM t.SOURCE
  JOIN dc d ON d.SOURCE IS NOT DISTINCT FROM t.SOURCE AND d.V IS NOT DISTINCT FROM t.CHANNEL),
hold AS (SELECT DISTINCT SOURCE, ZIP_CODE, CHANNEL AS DIST_CH, CLEAN_ID FROM t),
hz AS (SELECT DISTINCT SOURCE, ZIP_CODE, DIST_CH FROM hold),
hzp AS (SELECT DISTINCT SOURCE, ZIP_CODE, CLEAN_ID FROM hold),
opp_zc AS (SELECT ZIP_CODE, CHANNEL, SUM(MM_OPP) AS OPP FROM ux WHERE IS_CARRIER = 1 GROUP BY ZIP_CODE, CHANNEL),
sales_zc AS (SELECT SRC, ZIP_CODE, CHANNEL, SUM(POS) AS S FROM ux GROUP BY SRC, ZIP_CODE, CHANNEL),
carrier_src AS (SELECT l.SRC FROM lab l JOIN carrier c ON c.SOURCE = l.SOURCE),

colstats AS (        -- S01: per column and SOURCE
  SELECT 'union' AS TB, 'FISCAL_YR' AS COL, SRC, CAST(COUNT(DISTINCT FISCAL_YR) AS DOUBLE) AS D, COUNT(*) - COUNT(FISCAL_YR) AS NL,
         COUNT_IF(FISCAL_YR = '' OR FISCAL_YR <> TRIM(FISCAL_YR)) AS BL, MIN(LENGTH(FISCAL_YR)) AS LMIN, MAX(LENGTH(FISCAL_YR)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'SOURCE' AS COL, SRC, CAST(COUNT(DISTINCT SOURCE) AS DOUBLE) AS D, COUNT(*) - COUNT(SOURCE) AS NL,
         COUNT_IF(SOURCE = '' OR SOURCE <> TRIM(SOURCE)) AS BL, MIN(LENGTH(SOURCE)) AS LMIN, MAX(LENGTH(SOURCE)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'TERR_WHOLESALER' AS COL, SRC, CAST(COUNT(DISTINCT TERR_WHOLESALER) AS DOUBLE) AS D, COUNT(*) - COUNT(TERR_WHOLESALER) AS NL,
         COUNT_IF(TERR_WHOLESALER = '' OR TERR_WHOLESALER <> TRIM(TERR_WHOLESALER)) AS BL, MIN(LENGTH(TERR_WHOLESALER)) AS LMIN, MAX(LENGTH(TERR_WHOLESALER)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'SALES_WHOLESALER' AS COL, SRC, CAST(COUNT(DISTINCT SALES_WHOLESALER) AS DOUBLE) AS D, COUNT(*) - COUNT(SALES_WHOLESALER) AS NL,
         COUNT_IF(SALES_WHOLESALER = '' OR SALES_WHOLESALER <> TRIM(SALES_WHOLESALER)) AS BL, MIN(LENGTH(SALES_WHOLESALER)) AS LMIN, MAX(LENGTH(SALES_WHOLESALER)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'TERR_WHOLESALER_CLEAN_NAME' AS COL, SRC, CAST(COUNT(DISTINCT TERR_WHOLESALER_CLEAN_NAME) AS DOUBLE) AS D, COUNT(*) - COUNT(TERR_WHOLESALER_CLEAN_NAME) AS NL,
         COUNT_IF(TERR_WHOLESALER_CLEAN_NAME = '' OR TERR_WHOLESALER_CLEAN_NAME <> TRIM(TERR_WHOLESALER_CLEAN_NAME)) AS BL, MIN(LENGTH(TERR_WHOLESALER_CLEAN_NAME)) AS LMIN, MAX(LENGTH(TERR_WHOLESALER_CLEAN_NAME)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'SALES_WHOLESALER_CLEAN_NAME' AS COL, SRC, CAST(COUNT(DISTINCT SALES_WHOLESALER_CLEAN_NAME) AS DOUBLE) AS D, COUNT(*) - COUNT(SALES_WHOLESALER_CLEAN_NAME) AS NL,
         COUNT_IF(SALES_WHOLESALER_CLEAN_NAME = '' OR SALES_WHOLESALER_CLEAN_NAME <> TRIM(SALES_WHOLESALER_CLEAN_NAME)) AS BL, MIN(LENGTH(SALES_WHOLESALER_CLEAN_NAME)) AS LMIN, MAX(LENGTH(SALES_WHOLESALER_CLEAN_NAME)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'CBD_ID' AS COL, SRC, CAST(COUNT(DISTINCT CBD_ID) AS DOUBLE) AS D, COUNT(*) - COUNT(CBD_ID) AS NL,
         COUNT_IF(CBD_ID = '' OR CBD_ID <> TRIM(CBD_ID)) AS BL, MIN(LENGTH(CBD_ID)) AS LMIN, MAX(LENGTH(CBD_ID)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'FIRM' AS COL, SRC, CAST(COUNT(DISTINCT FIRM) AS DOUBLE) AS D, COUNT(*) - COUNT(FIRM) AS NL,
         COUNT_IF(FIRM = '' OR FIRM <> TRIM(FIRM)) AS BL, MIN(LENGTH(FIRM)) AS LMIN, MAX(LENGTH(FIRM)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'PARENT' AS COL, SRC, CAST(COUNT(DISTINCT PARENT) AS DOUBLE) AS D, COUNT(*) - COUNT(PARENT) AS NL,
         COUNT_IF(PARENT = '' OR PARENT <> TRIM(PARENT)) AS BL, MIN(LENGTH(PARENT)) AS LMIN, MAX(LENGTH(PARENT)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'DIST_CH' AS COL, SRC, CAST(COUNT(DISTINCT DIST_CH) AS DOUBLE) AS D, COUNT(*) - COUNT(DIST_CH) AS NL,
         COUNT_IF(DIST_CH = '' OR DIST_CH <> TRIM(DIST_CH)) AS BL, MIN(LENGTH(DIST_CH)) AS LMIN, MAX(LENGTH(DIST_CH)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'NEW_DIST' AS COL, SRC, CAST(COUNT(DISTINCT NEW_DIST) AS DOUBLE) AS D, COUNT(*) - COUNT(NEW_DIST) AS NL,
         COUNT_IF(NEW_DIST = '' OR NEW_DIST <> TRIM(NEW_DIST)) AS BL, MIN(LENGTH(NEW_DIST)) AS LMIN, MAX(LENGTH(NEW_DIST)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'CHANNEL' AS COL, SRC, CAST(COUNT(DISTINCT CHANNEL) AS DOUBLE) AS D, COUNT(*) - COUNT(CHANNEL) AS NL,
         COUNT_IF(CHANNEL = '' OR CHANNEL <> TRIM(CHANNEL)) AS BL, MIN(LENGTH(CHANNEL)) AS LMIN, MAX(LENGTH(CHANNEL)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'STATE' AS COL, SRC, CAST(COUNT(DISTINCT STATE) AS DOUBLE) AS D, COUNT(*) - COUNT(STATE) AS NL,
         COUNT_IF(STATE = '' OR STATE <> TRIM(STATE)) AS BL, MIN(LENGTH(STATE)) AS LMIN, MAX(LENGTH(STATE)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'ZIP_CODE' AS COL, SRC, CAST(COUNT(DISTINCT ZIP_CODE) AS DOUBLE) AS D, COUNT(*) - COUNT(ZIP_CODE) AS NL,
         COUNT_IF(ZIP_CODE = '' OR ZIP_CODE <> TRIM(ZIP_CODE)) AS BL, MIN(LENGTH(ZIP_CODE)) AS LMIN, MAX(LENGTH(ZIP_CODE)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'PRODUCT_V2' AS COL, SRC, CAST(COUNT(DISTINCT PRODUCT_V2) AS DOUBLE) AS D, COUNT(*) - COUNT(PRODUCT_V2) AS NL,
         COUNT_IF(PRODUCT_V2 = '' OR PRODUCT_V2 <> TRIM(PRODUCT_V2)) AS BL, MIN(LENGTH(PRODUCT_V2)) AS LMIN, MAX(LENGTH(PRODUCT_V2)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'SALES_WHOLESALER_TERRITORY_ID' AS COL, SRC, CAST(COUNT(DISTINCT SALES_WHOLESALER_TERRITORY_ID) AS DOUBLE) AS D, COUNT(*) - COUNT(SALES_WHOLESALER_TERRITORY_ID) AS NL,
         COUNT_IF(SALES_WHOLESALER_TERRITORY_ID = '' OR SALES_WHOLESALER_TERRITORY_ID <> TRIM(SALES_WHOLESALER_TERRITORY_ID)) AS BL, MIN(LENGTH(SALES_WHOLESALER_TERRITORY_ID)) AS LMIN, MAX(LENGTH(SALES_WHOLESALER_TERRITORY_ID)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'SALES_WHOLESALER_ADDRESS_ID' AS COL, SRC, CAST(COUNT(DISTINCT SALES_WHOLESALER_ADDRESS_ID) AS DOUBLE) AS D, COUNT(*) - COUNT(SALES_WHOLESALER_ADDRESS_ID) AS NL,
         COUNT_IF(SALES_WHOLESALER_ADDRESS_ID = '' OR SALES_WHOLESALER_ADDRESS_ID <> TRIM(SALES_WHOLESALER_ADDRESS_ID)) AS BL, MIN(LENGTH(SALES_WHOLESALER_ADDRESS_ID)) AS LMIN, MAX(LENGTH(SALES_WHOLESALER_ADDRESS_ID)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'TERRITORY_WHOLESALER_TERRITORY_ID' AS COL, SRC, CAST(COUNT(DISTINCT TERRITORY_WHOLESALER_TERRITORY_ID) AS DOUBLE) AS D, COUNT(*) - COUNT(TERRITORY_WHOLESALER_TERRITORY_ID) AS NL,
         COUNT_IF(TERRITORY_WHOLESALER_TERRITORY_ID = '' OR TERRITORY_WHOLESALER_TERRITORY_ID <> TRIM(TERRITORY_WHOLESALER_TERRITORY_ID)) AS BL, MIN(LENGTH(TERRITORY_WHOLESALER_TERRITORY_ID)) AS LMIN, MAX(LENGTH(TERRITORY_WHOLESALER_TERRITORY_ID)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union' AS TB, 'TERRITORY_WHOLESALER_ADDRESS_ID' AS COL, SRC, CAST(COUNT(DISTINCT TERRITORY_WHOLESALER_ADDRESS_ID) AS DOUBLE) AS D, COUNT(*) - COUNT(TERRITORY_WHOLESALER_ADDRESS_ID) AS NL,
         COUNT_IF(TERRITORY_WHOLESALER_ADDRESS_ID = '' OR TERRITORY_WHOLESALER_ADDRESS_ID <> TRIM(TERRITORY_WHOLESALER_ADDRESS_ID)) AS BL, MIN(LENGTH(TERRITORY_WHOLESALER_ADDRESS_ID)) AS LMIN, MAX(LENGTH(TERRITORY_WHOLESALER_ADDRESS_ID)) AS LMAX FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union', 'MM_OPP', SRC, COUNT(DISTINCT MM_OPP), COUNT(*) - COUNT(MM_OPP), 0, NULL, NULL FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union', 'ACTUAL_SALES_AMOUNT', SRC, COUNT(DISTINCT ACTUAL_SALES_AMOUNT), COUNT(*) - COUNT(ACTUAL_SALES_AMOUNT), 0, NULL, NULL FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union', 'SALES_AMOUNT', SRC, COUNT(DISTINCT SALES_AMOUNT), COUNT(*) - COUNT(SALES_AMOUNT), 0, NULL, NULL FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union', 'SALES_WHOLESALER_HAS_TERRITORY', SRC, COUNT(DISTINCT SALES_WHOLESALER_HAS_TERRITORY), COUNT(*) - COUNT(SALES_WHOLESALER_HAS_TERRITORY), 0, NULL, NULL FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'union', 'TERRITORY_WHOLESALER_HAS_TERRITORY', SRC, COUNT(DISTINCT TERRITORY_WHOLESALER_HAS_TERRITORY), COUNT(*) - COUNT(TERRITORY_WHOLESALER_HAS_TERRITORY), 0, NULL, NULL FROM ux GROUP BY SRC
  UNION ALL
  SELECT 'territories' AS TB, 'SOURCE' AS COL, SRC, CAST(COUNT(DISTINCT SOURCE) AS DOUBLE) AS D, COUNT(*) - COUNT(SOURCE) AS NL,
         COUNT_IF(SOURCE = '' OR SOURCE <> TRIM(SOURCE)) AS BL, MIN(LENGTH(SOURCE)) AS LMIN, MAX(LENGTH(SOURCE)) AS LMAX FROM tx GROUP BY SRC
  UNION ALL
  SELECT 'territories' AS TB, 'NAME' AS COL, SRC, CAST(COUNT(DISTINCT NAME) AS DOUBLE) AS D, COUNT(*) - COUNT(NAME) AS NL,
         COUNT_IF(NAME = '' OR NAME <> TRIM(NAME)) AS BL, MIN(LENGTH(NAME)) AS LMIN, MAX(LENGTH(NAME)) AS LMAX FROM tx GROUP BY SRC
  UNION ALL
  SELECT 'territories' AS TB, 'ZIP_CODE' AS COL, SRC, CAST(COUNT(DISTINCT ZIP_CODE) AS DOUBLE) AS D, COUNT(*) - COUNT(ZIP_CODE) AS NL,
         COUNT_IF(ZIP_CODE = '' OR ZIP_CODE <> TRIM(ZIP_CODE)) AS BL, MIN(LENGTH(ZIP_CODE)) AS LMIN, MAX(LENGTH(ZIP_CODE)) AS LMAX FROM tx GROUP BY SRC
  UNION ALL
  SELECT 'territories' AS TB, 'STATE' AS COL, SRC, CAST(COUNT(DISTINCT STATE) AS DOUBLE) AS D, COUNT(*) - COUNT(STATE) AS NL,
         COUNT_IF(STATE = '' OR STATE <> TRIM(STATE)) AS BL, MIN(LENGTH(STATE)) AS LMIN, MAX(LENGTH(STATE)) AS LMAX FROM tx GROUP BY SRC
  UNION ALL
  SELECT 'territories' AS TB, 'CHANNEL' AS COL, SRC, CAST(COUNT(DISTINCT CHANNEL) AS DOUBLE) AS D, COUNT(*) - COUNT(CHANNEL) AS NL,
         COUNT_IF(CHANNEL = '' OR CHANNEL <> TRIM(CHANNEL)) AS BL, MIN(LENGTH(CHANNEL)) AS LMIN, MAX(LENGTH(CHANNEL)) AS LMAX FROM tx GROUP BY SRC
  UNION ALL
  SELECT 'territories' AS TB, 'CLEAN_NAME' AS COL, SRC, CAST(COUNT(DISTINCT CLEAN_NAME) AS DOUBLE) AS D, COUNT(*) - COUNT(CLEAN_NAME) AS NL,
         COUNT_IF(CLEAN_NAME = '' OR CLEAN_NAME <> TRIM(CLEAN_NAME)) AS BL, MIN(LENGTH(CLEAN_NAME)) AS LMIN, MAX(LENGTH(CLEAN_NAME)) AS LMAX FROM tx GROUP BY SRC
  UNION ALL
  SELECT 'territories' AS TB, 'CLEAN_ID' AS COL, SRC, CAST(COUNT(DISTINCT CLEAN_ID) AS DOUBLE) AS D, COUNT(*) - COUNT(CLEAN_ID) AS NL,
         COUNT_IF(CLEAN_ID = '' OR CLEAN_ID <> TRIM(CLEAN_ID)) AS BL, MIN(LENGTH(CLEAN_ID)) AS LMIN, MAX(LENGTH(CLEAN_ID)) AS LMAX FROM tx GROUP BY SRC
),
dcc AS (             -- S03: per (SOURCE, DIST_CH, CHANNEL) in the union table
  SELECT SRC, DC, COALESCE(CHANNEL, 'NULL') AS CH, COUNT(*) AS ROWS_, COUNT(DISTINCT ZIP_CODE) AS ZIPS,
         100 * SUM(POS) / NULLIF(SUM(SUM(POS)) OVER (PARTITION BY SRC), 0) AS PCT_SALES,
         100 * SUM(COALESCE(MM_OPP, 0)) / NULLIF(SUM(SUM(COALESCE(MM_OPP, 0))) OVER (), 0) AS PCT_OPP,
         COUNT(DISTINCT CASE WHEN POS > 0 THEN PRODUCT_V2 END) AS PRODUCTS_SOLD,
         COUNT(DISTINCT CASE WHEN COALESCE(MM_OPP, 0) <> 0 THEN PRODUCT_V2 END) AS PRODUCTS_OPP
  FROM ux GROUP BY SRC, DC, COALESCE(CHANNEL, 'NULL')),
d4u AS (SELECT SRC, DC, COUNT(DISTINCT CHANNEL) AS CHS, COUNT(DISTINCT ZIP_CODE) AS ZIPS,
               COUNT(DISTINCT NEW_DIST) AS NEW_DISTS FROM ux GROUP BY SRC, DC),
d4t AS (SELECT SRC, DC, COUNT(DISTINCT CLEAN_ID) AS PEOPLE, COUNT(DISTINCT ZIP_CODE) AS ZIPS FROM tx GROUP BY SRC, DC),
d4 AS (
  SELECT l.SRC, d.DC, d.UN, d.TN, a.CHS, a.ZIPS AS UZIPS, a.NEW_DISTS, b.PEOPLE, b.ZIPS AS TZIPS
  FROM dc d JOIN lab l ON l.SOURCE IS NOT DISTINCT FROM d.SOURCE
  LEFT JOIN d4u a ON a.SRC = l.SRC AND a.DC = d.DC
  LEFT JOIN d4t b ON b.SRC = l.SRC AND b.DC = d.DC),
prod AS (            -- S05: per (SOURCE, PRODUCT_V2)
  SELECT SRC, PC, COUNT(*) AS ROWS_,
         100 * SUM(POS) / NULLIF(SUM(SUM(POS)) OVER (PARTITION BY SRC), 0) AS PCT_SALES,
         100 * SUM(COALESCE(MM_OPP, 0)) / NULLIF(SUM(SUM(COALESCE(MM_OPP, 0))) OVER (), 0) AS PCT_OPP,
         COUNT_IF(COALESCE(MM_OPP, 0) <> 0) AS OPP_ROWS,
         COUNT(DISTINCT CASE WHEN POS > 0 THEN CHANNEL END) AS CHS_SOLD
  FROM ux GROUP BY SRC, PC),
g1o AS (             -- S06: MM_OPP within a (ZIP_CODE, DIST_CH, CHANNEL, PRODUCT_V2) cell, carrier
  SELECT SRC, COUNT_IF(COALESCE(MM_OPP, 0) <> 0) AS NZ,
         MIN(CASE WHEN MM_OPP <> 0 THEN MM_OPP END) AS MN, MAX(CASE WHEN MM_OPP <> 0 THEN MM_OPP END) AS MX
  FROM ux WHERE IS_CARRIER = 1
  GROUP BY SRC, ZIP_CODE, DIST_CH, CHANNEL, PRODUCT_V2),
loc AS (             -- S08: where each SOURCE's positive sales fall against the territories table
  SELECT x.SRC,
         CASE WHEN x.SALES_WHOLESALER_TERRITORY_ID IS NULL THEN 'seller ID NULL'
              WHEN h.CLEAN_ID IS NOT NULL THEN 'seller holds the ZIP_CODE and DIST_CH'
              WHEN p.CLEAN_ID IS NOT NULL THEN 'seller holds the ZIP_CODE in another DIST_CH'
              WHEN z.ZIP_CODE IS NOT NULL THEN 'someone else of this SOURCE holds the ZIP_CODE and DIST_CH'
              ELSE 'nobody of this SOURCE holds the ZIP_CODE and DIST_CH' END AS WHERE_,
         SUM(x.POS) AS S
  FROM ux x
  LEFT JOIN hold h ON h.SOURCE = x.SOURCE AND h.ZIP_CODE = x.ZIP_CODE AND h.DIST_CH = x.DIST_CH
                  AND h.CLEAN_ID = x.SALES_WHOLESALER_TERRITORY_ID
  LEFT JOIN hzp p ON p.SOURCE = x.SOURCE AND p.ZIP_CODE = x.ZIP_CODE AND p.CLEAN_ID = x.SALES_WHOLESALER_TERRITORY_ID
  LEFT JOIN hz z ON z.SOURCE = x.SOURCE AND z.ZIP_CODE = x.ZIP_CODE AND z.DIST_CH = x.DIST_CH
  GROUP BY 1, 2),
ids AS (             -- S08: the people IDs on union rows
  SELECT DISTINCT SRC, 'SALES_WHOLESALER_TERRITORY_ID' AS COL, SALES_WHOLESALER_TERRITORY_ID AS ID,
         SALES_WHOLESALER_HAS_TERRITORY AS FLAG
  FROM ux WHERE SALES_WHOLESALER_TERRITORY_ID IS NOT NULL
  UNION ALL
  SELECT DISTINCT SRC, 'TERRITORY_WHOLESALER_TERRITORY_ID', TERRITORY_WHOLESALER_TERRITORY_ID,
         TERRITORY_WHOLESALER_HAS_TERRITORY
  FROM ux WHERE TERRITORY_WHOLESALER_TERRITORY_ID IS NOT NULL),
tid AS (SELECT DISTINCT SRC, CLEAN_ID FROM tx),
seller_own AS (      -- per seller: share of their positive sales in a (ZIP_CODE, DIST_CH) they hold
  SELECT x.SRC, x.SALES_WHOLESALER_TERRITORY_ID AS ID,
         SUM(CASE WHEN h.CLEAN_ID IS NOT NULL THEN x.POS ELSE 0 END) / NULLIF(SUM(x.POS), 0) AS OWN
  FROM ux x
  LEFT JOIN hold h ON h.SOURCE = x.SOURCE AND h.ZIP_CODE = x.ZIP_CODE AND h.DIST_CH = x.DIST_CH
                  AND h.CLEAN_ID = x.SALES_WHOLESALER_TERRITORY_ID
  WHERE x.SALES_WHOLESALER_TERRITORY_ID IS NOT NULL
  GROUP BY x.SRC, x.SALES_WHOLESALER_TERRITORY_ID),
zipst AS (SELECT 'union' AS TB, ZIP_CODE, STATE FROM u UNION SELECT 'territories', ZIP_CODE, STATE FROM t),

facts AS (
  -- S00 overview
  SELECT 'S00 overview' AS SECTION, SRC, '-' AS K1, '-' AS K2, 'union rows' AS METRIC, CAST(COUNT(*) AS DOUBLE) AS VALUE
  FROM ux GROUP BY SRC
  UNION ALL SELECT 'S00 overview', SRC, '-', '-', 'territories rows', COUNT(*) FROM tx GROUP BY SRC
  UNION ALL SELECT 'S00 overview', l.SRC, '-', '-', 'carries MM_OPP (1 = yes)', CASE WHEN c.SOURCE IS NULL THEN 0 ELSE 1 END
  FROM lab l LEFT JOIN carrier c ON c.SOURCE = l.SOURCE
  UNION ALL SELECT 'S00 overview', 'all', '-', '-', 'PRODUCT_V2 values', COUNT(*) FROM pc

  -- S01 columns
  UNION ALL SELECT 'S01 columns', SRC, TB, COL, 'distinct values', D FROM colstats
  UNION ALL SELECT 'S01 columns', SRC, TB, COL, 'NULL rows', NL FROM colstats WHERE NL > 0
  UNION ALL SELECT 'S01 columns', SRC, TB, COL, 'empty or space-padded rows', BL FROM colstats WHERE BL > 0
  UNION ALL SELECT 'S01 columns', SRC, TB, COL, 'length min', LMIN FROM colstats WHERE LMIN IS NOT NULL
  UNION ALL SELECT 'S01 columns', SRC, TB, COL, 'length max', LMAX FROM colstats WHERE LMAX IS NOT NULL

  -- S02 grain: distinct keys; equal to the rows in S00 means the key is unique
  UNION ALL SELECT 'S02 grain', SRC, 'union', 'ZIP_CODE DIST_CH CHANNEL PRODUCT_V2', 'distinct keys', COUNT(*)
  FROM (SELECT DISTINCT SRC, ZIP_CODE, DIST_CH, CHANNEL, PRODUCT_V2 FROM ux) x GROUP BY SRC
  UNION ALL SELECT 'S02 grain', SRC, 'union', '+ SALES_WHOLESALER_TERRITORY_ID', 'distinct keys', COUNT(*)
  FROM (SELECT DISTINCT SRC, ZIP_CODE, DIST_CH, CHANNEL, PRODUCT_V2, SALES_WHOLESALER_TERRITORY_ID FROM ux) x GROUP BY SRC
  UNION ALL SELECT 'S02 grain', SRC, 'union', '+ TERRITORY_WHOLESALER_TERRITORY_ID', 'distinct keys', COUNT(*)
  FROM (SELECT DISTINCT SRC, ZIP_CODE, DIST_CH, CHANNEL, PRODUCT_V2, SALES_WHOLESALER_TERRITORY_ID,
               TERRITORY_WHOLESALER_TERRITORY_ID FROM ux) x GROUP BY SRC
  UNION ALL SELECT 'S02 grain', SRC, 'union', '+ FIRM CBD_ID', 'distinct keys', COUNT(*)
  FROM (SELECT DISTINCT SRC, ZIP_CODE, DIST_CH, CHANNEL, PRODUCT_V2, SALES_WHOLESALER_TERRITORY_ID,
               TERRITORY_WHOLESALER_TERRITORY_ID, FIRM, CBD_ID FROM ux) x GROUP BY SRC
  UNION ALL SELECT 'S02 grain', SRC, 'union', '+ NEW_DIST STATE both ADDRESS_IDs', 'distinct keys', COUNT(*)
  FROM (SELECT DISTINCT SRC, ZIP_CODE, DIST_CH, CHANNEL, PRODUCT_V2, SALES_WHOLESALER_TERRITORY_ID,
               TERRITORY_WHOLESALER_TERRITORY_ID, FIRM, CBD_ID, NEW_DIST, STATE,
               SALES_WHOLESALER_ADDRESS_ID, TERRITORY_WHOLESALER_ADDRESS_ID FROM ux) x GROUP BY SRC
  UNION ALL SELECT 'S02 grain', l.SRC, 'union', 'all columns', 'distinct keys', COUNT(*)
  FROM (SELECT DISTINCT * FROM u) x JOIN lab l ON l.SOURCE IS NOT DISTINCT FROM x.SOURCE GROUP BY l.SRC
  UNION ALL SELECT 'S02 grain', SRC, 'territories', 'ZIP_CODE CHANNEL', 'distinct keys', COUNT(*)
  FROM (SELECT DISTINCT SRC, ZIP_CODE, CHANNEL FROM tx) x GROUP BY SRC
  UNION ALL SELECT 'S02 grain', SRC, 'territories', 'ZIP_CODE CHANNEL CLEAN_ID', 'distinct keys', COUNT(*)
  FROM (SELECT DISTINCT SRC, ZIP_CODE, CHANNEL, CLEAN_ID FROM tx) x GROUP BY SRC
