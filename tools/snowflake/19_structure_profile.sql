         PERCENTILE_CONT(0.10) WITHIN GROUP (ORDER BY X) AS P10,
         PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY X) AS P25,
         PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY X) AS P50,
         PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY X) AS P75,
         PERCENTILE_CONT(0.90) WITHIN GROUP (ORDER BY X) AS P90,
         PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY X) AS P99,
         MAX(X) AS PMAX
  FROM dist GROUP BY SECTION, SRC, K1, K2, METRIC, REL)

SELECT SECTION, SRC AS SOURCE, K1, K2, METRIC, ROUND(VALUE, 4) AS VALUE,
       CAST(NULL AS DOUBLE) AS PMIN, CAST(NULL AS DOUBLE) AS P10, CAST(NULL AS DOUBLE) AS P25,
       CAST(NULL AS DOUBLE) AS P50, CAST(NULL AS DOUBLE) AS P75, CAST(NULL AS DOUBLE) AS P90,
       CAST(NULL AS DOUBLE) AS P99, CAST(NULL AS DOUBLE) AS PMAX
FROM facts
UNION ALL
SELECT SECTION, SRC, K1, K2, METRIC || CASE WHEN REL = 1 THEN ' / median' ELSE '' END, N,
       ROUND(PMIN / M, 4), ROUND(P10 / M, 4), ROUND(P25 / M, 4), ROUND(P50 / M, 4),
       ROUND(P75 / M, 4), ROUND(P90 / M, 4), ROUND(P99 / M, 4), ROUND(PMAX / M, 4)
FROM (SELECT dq.*, CASE WHEN REL = 1 THEN NULLIF(P50, 0) ELSE 1 END AS M FROM dq) d
ORDER BY 1, 2, 3, 4, 5;
